// RL-NX: the two runtime utilities that live in src/runtime/main.cpp on PC.
//
// main.cpp is the desktop application - SDL window, launcher, settings menu, restart - and is not
// part of the Switch build (switch/CMakeLists.txt, RL_RUNTIME_PARKED). It also happens to define
// rt::logf and rt::describeAddr, which the guest core calls (cpu.cpp's fatal paths, threads.cpp's
// backtrace), so this file provides those two for the Switch build. Everything else the guest core
// needs from main.cpp (discOpen, the frame loop) comes with the real entry point in a later step.
#include <cstdarg>
#include <cstdio>
#include <string>

#include <switch.h>

#include "log_switch.h"  // melee_nx_log_write: the port's async log (SD card file + console)
#include "runtime.h"     // rt::logf, rt::describeAddr
#include "table.h"       // g_symNames (generated by the recompiler)

namespace rt {

// Same shape as the desktop log line, so a log from the console reads like a log from the PC:
// "  123.456 cpu    message". The timestamp is Switch ticks (19.2 MHz), not the guest time base:
// rt::tbNow() is defined in main.cpp, and the guest time base only starts once the guest does.
void logf(const char* tag, const char* fmt, ...) {
    char msg[2048];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);

    static u64 s_t0 = svcGetSystemTick();
    const double t = double(svcGetSystemTick() - s_t0) / 19200000.0;
    char line[2200];
    const int n = snprintf(line, sizeof line, "[%9.3f %-6s] %s\n", t, tag, msg);
    if (n > 0) melee_nx_log_write(line, size_t(n < int(sizeof line) ? n : sizeof line - 1));
}

// Guest addresses in a fatal message: "80123456 (fn_80123456)" when the recompiler emitted a name
// for that address, plain hex otherwise. The symbol table is the one the game library carries.
std::string describeAddr(u32 addr) {
    char buf[512];
    for (const SymName* s = g_symNames; s->name; s++) {
        if (s->addr == addr) {
            snprintf(buf, sizeof buf, "%08X (%s)", addr, s->name);
            return buf;
        }
    }
    snprintf(buf, sizeof buf, "%08X", addr);
    return buf;
}

// A guest word for the thread dump (threads.cpp's guestBacktrace), read the way the desktop does:
// through the VM page table when the address is in virtual memory, straight into the arena when it
// is MEM1, and 0 for anything else. It must not fault, which is why it goes through the page table
// instead of a raw pointer: the guest may be mid-teardown when a dump happens.
u32 peekGuest32(u32 a) {
    u8* p;
    if (isVm(a)) {
        p = g_vmRead[(a - kVmStart) >> 12];
        if (!p) return 0;
        p += a & 0xFFF;
    } else if (isMem1(a)) {
        p = hp(a);
    } else {
        return 0;
    }
    return (u32(p[0]) << 24) | (u32(p[1]) << 16) | (u32(p[2]) << 8) | p[3];
}

}  // namespace rt

// Declared and called by switch/src/clang_tls_switch.c (thread creation, exit and restart paths). On the
// other ports it lives in their main_switch.cpp; here it is a line in the port's log with a [boot] tag,
// so the thread accounting around exit reads as a timeline next to everything else.
extern "C" void melee_boot_trace(const char* fmt, ...) {
    char msg[1024];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);
    char line[1100];
    const int n = snprintf(line, sizeof line, "[boot] %s\n", msg);
    if (n > 0) melee_nx_log_write(line, size_t(n < int(sizeof line) ? n : sizeof line - 1));
}

